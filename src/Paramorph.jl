intrinsic_dimension(T::Type; context=NamedTuple()) =
    TransformVariables.dimension(transformation_schema(T, context))
intrinsic_dimension(object; context=NamedTuple()) =
    TransformVariables.dimension(transformation_schema(object, context))

parameter_values(object; context=NamedTuple()) = begin
    values = NamedTuple{fieldnames(typeof(object))}(Tuple(getfield(object, field) for field in fieldnames(typeof(object))))
    _parameter_values_from_values(typeof(object), values, context)
end

function constraint(T::Type, coordinates::AbstractVector{<:Real}; context=NamedTuple())
    supports_type_geometry(T) || throw(ArgumentError(
        "$T has value-dependent parameter geometry; use a prototype object",
    ))
    target = rebind_numeric_type(T, eltype(coordinates))
    schema = transformation_schema(target, context)
    length(coordinates) == TransformVariables.dimension(schema) || throw(DimensionMismatch(
        "expected $(TransformVariables.dimension(schema)) coordinates, got $(length(coordinates))",
    ))
    constrained = TransformVariables.transform(schema, coordinates)
    return _reconstruct_declared_from_type(target, constrained, context)
end

function constraint(prototype, coordinates::AbstractVector{<:Real}; context=NamedTuple())
    schema = transformation_schema(prototype, context)
    length(coordinates) == TransformVariables.dimension(schema) || throw(DimensionMismatch(
        "expected $(TransformVariables.dimension(schema)) coordinates, got $(length(coordinates))",
    ))
    target = rebind_numeric_type(typeof(prototype), eltype(coordinates))
    constrained = TransformVariables.transform(schema, coordinates)
    return _reconstruct_declared_from_prototype(prototype, target, constrained, context)
end

function constraint_with_logjac(T::Type, coordinates::AbstractVector{<:Real}; context=NamedTuple())
    supports_type_geometry(T) || throw(ArgumentError(
        "$T has value-dependent parameter geometry; use a prototype object",
    ))
    target = rebind_numeric_type(T, eltype(coordinates))
    schema = transformation_schema(target, context)
    length(coordinates) == TransformVariables.dimension(schema) || throw(DimensionMismatch(
        "expected $(TransformVariables.dimension(schema)) coordinates, got $(length(coordinates))",
    ))
    constrained, logjac = TransformVariables.transform_and_logjac(schema, coordinates)
    return _reconstruct_declared_from_type(target, constrained, context), logjac
end

function constraint_with_logjac(prototype, coordinates::AbstractVector{<:Real}; context=NamedTuple())
    schema = transformation_schema(prototype, context)
    length(coordinates) == TransformVariables.dimension(schema) || throw(DimensionMismatch(
        "expected $(TransformVariables.dimension(schema)) coordinates, got $(length(coordinates))",
    ))
    constrained, logjac = TransformVariables.transform_and_logjac(schema, coordinates)
    target = rebind_numeric_type(typeof(prototype), eltype(coordinates))
    return _reconstruct_declared_from_prototype(prototype, target, constrained, context), logjac
end

function unconstrain(object; context=NamedTuple())
    schema = transformation_schema(object, context)
    return TransformVariables.inverse(schema, parameter_values(object; context))
end

# -----------------------------------------------------------------------------
# Validation
# -----------------------------------------------------------------------------

function _same_constrained(a::NamedTuple, b::NamedTuple)
    keys(a) == keys(b) || return false
    return all(_same_constrained(a[name], b[name]) for name in keys(a))
end
function _same_constrained(a::AbstractArray, b::AbstractArray)
    axes(a) == axes(b) || return false
    return all(_same_constrained(x, y) for (x, y) in zip(a, b))
end
_same_constrained(a::Number, b::Number) = isapprox(a, b; nans=true)
_same_constrained(a, b) = isequal(a, b)

function validate_constrained(T::Type, values::NamedTuple)
    schema = _schema_from_values(T, values, NamedTuple())
    constrained = _parameter_values_from_values(T, values, NamedTuple())
    coordinates = try
        TransformVariables.inverse(schema, constrained)
    catch error
        error isa Union{DomainError, ArgumentError, DimensionMismatch} || rethrow()
        throw(DomainError(values, "the parameter fields of $T do not satisfy their declared geometry"))
    end
    roundtrip = TransformVariables.transform(schema, coordinates)
    _same_constrained(constrained, roundtrip) || throw(DomainError(
        values,
        "the parameter fields of $T are not in the image of their declared geometry",
    ))
    return nothing
end

