"""
    nested(; context...)

Use the parameter geometry declared by a nested `@paramorph` field. Keyword
arguments become the child's `context` named tuple.
"""
struct NestedSpec{C}
    context::C
end
nested(; kwargs...) = NestedSpec((; kwargs...))

"""
    recursive([count]; context...)

Use the parameter geometry of `@paramorph` objects stored recursively in a
container. A vector needs either an explicit `count` or a prototype value.
"""
struct RecursiveSpec{C}
    count::Union{Nothing,Int}
    context::C
end
recursive(; kwargs...) = RecursiveSpec(nothing, (; kwargs...))
function recursive(count::Integer; kwargs...)
    count >= 0 || throw(ArgumentError("recursive count must be nonnegative"))
    return RecursiveSpec(Int(count), (; kwargs...))
end

