function _reconstruct_nested(::Type{F}, constrained::NamedTuple, context::NamedTuple) where {F}
    return _reconstruct_declared_from_type(F, constrained, context)
end
function _reconstruct_nested(prototype, ::Type{F}, constrained::NamedTuple, context::NamedTuple) where {F}
    return _reconstruct_declared_from_prototype(prototype, F, constrained, context)
end

_reconstruct_geometry(::Any, ::Type{F}, constrained) where {F} = constrained
_reconstruct_geometry(::Any, prototype, ::Type{F}, constrained) where {F} = constrained

_reconstruct_geometry(spec::NestedSpec, ::Type{F}, constrained) where {F} =
    _reconstruct_nested(F, constrained, spec.context)
_reconstruct_geometry(spec::NestedSpec, prototype, ::Type{F}, constrained) where {F} =
    _reconstruct_nested(prototype, F, constrained, spec.context)

function _reconstruct_geometry(spec::RecursiveSpec, ::Type{V}, constrained) where {E,V<:AbstractVector{E}}
    return E[_reconstruct_nested(E, value, spec.context) for value in constrained]
end
function _reconstruct_geometry(spec::RecursiveSpec, prototype::AbstractVector, ::Type{V}, constrained) where {E,V<:AbstractVector{E}}
    length(prototype) == length(constrained) || throw(DimensionMismatch("recursive vector shape changed"))
    return E[_reconstruct_nested(old, E, value, spec.context) for (old, value) in zip(prototype, constrained)]
end
function _reconstruct_geometry(spec::RecursiveSpec, ::Type{T}, constrained::Tuple) where {T<:Tuple}
    return map((type, value) -> _reconstruct_nested(type, value, spec.context), T.parameters, constrained)
end
function _reconstruct_geometry(spec::RecursiveSpec, prototype::Tuple, ::Type{T}, constrained::Tuple) where {T<:Tuple}
    return map((old, type, value) -> _reconstruct_nested(old, type, value, spec.context), prototype, T.parameters, constrained)
end
function _reconstruct_geometry(spec::RecursiveSpec, ::Type{N}, constrained::NamedTuple) where {Names,Types,N<:NamedTuple{Names,Types}}
    vals = map((type, value) -> _reconstruct_nested(type, value, spec.context), Types.parameters, Tuple(constrained))
    return NamedTuple{Names}(vals)
end
function _reconstruct_geometry(spec::RecursiveSpec, prototype::NamedTuple, ::Type{N}, constrained::NamedTuple) where {Names,Types,N<:NamedTuple{Names,Types}}
    vals = map(
        (old, type, value) -> _reconstruct_nested(old, type, value, spec.context),
        Tuple(prototype), Types.parameters, Tuple(constrained),
    )
    return NamedTuple{Names}(vals)
end

function _reconstruct_from_type(T::Type, constrained::NamedTuple)
    defaults = auxiliary_defaults(T)
    fields = map(fieldnames(T)) do field
        if hasproperty(constrained, field)
            return getproperty(constrained, field)
        elseif hasproperty(defaults, field)
            return getproperty(defaults, field)
        end
        throw(ArgumentError(
            "$T has no default for auxiliary field $field; use a prototype object",
        ))
    end
    return T(_trusted_construction, fields...)
end

function _reconstruct_from_prototype(prototype, T::Type, constrained::NamedTuple)
    fields = map(fieldnames(T)) do field
        hasproperty(constrained, field) ? getproperty(constrained, field) : getproperty(prototype, field)
    end
    return T(_trusted_construction, fields...)
end

# Macro-generated methods specialize these two hooks so that nested/recursive
# fields are reconstructed according to their declared geometry descriptor.
_reconstruct_declared_from_type(T::Type, constrained::NamedTuple, context::NamedTuple) =
    _reconstruct_from_type(T, constrained)
_reconstruct_declared_from_prototype(prototype, T::Type, constrained::NamedTuple, context::NamedTuple) =
    _reconstruct_from_prototype(prototype, T, constrained)

