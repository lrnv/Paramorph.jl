struct _TrustedConstruction end
const _trusted_construction = _TrustedConstruction()

is_paramorph_type(::Type) = false
parameter_fields(::Type) = ()
auxiliary_fields(::Type) = ()
auxiliary_defaults(::Type) = NamedTuple()
numeric_type(::Type) = nothing
rebind_numeric_type(T::Type, ::Type) = T
supports_type_geometry(::Type) = false

function transformation_schema(T::Type, context::NamedTuple=NamedTuple())
    throw(ArgumentError("$T does not declare a Paramorph geometry"))
end
transformation_schema(object, context::NamedTuple=NamedTuple()) =
    transformation_schema(typeof(object), context)

function _schema_from_values(T::Type, values::NamedTuple, context::NamedTuple)
    throw(ArgumentError("$T does not declare a Paramorph geometry"))
end

function _parameter_values_from_values(T::Type, values::NamedTuple, context::NamedTuple)
    throw(ArgumentError("$T does not declare Paramorph parameters"))
end

# Turn a DSL right-hand side into the TransformVariables transformation used by
# the enclosing product schema. Ordinary transforms pass through untouched.
_materialize_geometry(t, ::Type, value, ::Bool) = t

function _materialize_geometry(spec::NestedSpec, ::Type{F}, value, has_value::Bool) where {F}
    return has_value ? transformation_schema(value, spec.context) :
        transformation_schema(F, spec.context)
end

function _materialize_geometry(spec::RecursiveSpec, ::Type{F}, value, has_value::Bool) where {F}
    return has_value ? _recursive_schema(value, spec.count, spec.context) :
        _recursive_schema(F, spec.count, spec.context)
end

_geometry_value(::Any, value) = value
_geometry_value(::NestedSpec, value) = parameter_values(value)
_geometry_value(spec::RecursiveSpec, value) = _recursive_parameter_values(value)

function _recursive_schema(::Type{V}, count, context) where {E,V<:AbstractVector{E}}
    isnothing(count) && throw(ArgumentError(
        "$V needs a recursive count when its geometry is built from the type alone",
    ))
    return repeat_transform(transformation_schema(E, context), count)
end
function _recursive_schema(values::AbstractVector, count, context)
    n = isnothing(count) ? length(values) : count
    n == length(values) || throw(DimensionMismatch(
        "recursive count $n does not match vector length $(length(values))",
    ))
    if isempty(values)
        E = eltype(values)
        return repeat_transform(transformation_schema(E, context), 0)
    end
    schemas = map(value -> transformation_schema(value, context), values)
    first_schema = first(schemas)
    all(schema -> isequal(schema, first_schema), schemas) || throw(ArgumentError(
        "recursive vectors currently require elements with homogeneous parameter geometries",
    ))
    return repeat_transform(first_schema, n)
end
function _recursive_schema(::Type{T}, count, context) where {T<:Tuple}
    isnothing(count) || count == length(T.parameters) || throw(DimensionMismatch(
        "recursive count $count does not match tuple length $(length(T.parameters))",
    ))
    return TransformVariables.as(Tuple(map(type -> transformation_schema(type, context), T.parameters)))
end
function _recursive_schema(values::Tuple, count, context)
    isnothing(count) || count == length(values) || throw(DimensionMismatch(
        "recursive count $count does not match tuple length $(length(values))",
    ))
    return TransformVariables.as(map(value -> transformation_schema(value, context), values))
end
function _recursive_schema(::Type{N}, count, context) where {Names,Types,N<:NamedTuple{Names,Types}}
    isnothing(count) || count == length(Types.parameters) || throw(DimensionMismatch(
        "recursive count $count does not match named tuple length $(length(Types.parameters))",
    ))
    schemas = Tuple(map(type -> transformation_schema(type, context), Types.parameters))
    return TransformVariables.as(NamedTuple{Names}(schemas))
end
function _recursive_schema(values::NamedTuple, count, context)
    isnothing(count) || count == length(values) || throw(DimensionMismatch(
        "recursive count $count does not match named tuple length $(length(values))",
    ))
    return TransformVariables.as(map(value -> transformation_schema(value, context), values))
end

_recursive_parameter_values(values::AbstractVector) = map(parameter_values, values)
_recursive_parameter_values(values::Tuple) = map(parameter_values, values)
_recursive_parameter_values(values::NamedTuple) = map(parameter_values, values)

