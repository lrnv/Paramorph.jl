_field_name_from_decl(expr) = expr isa Expr && expr.head == :(::) && expr.args[1] isa Symbol ? expr.args[1] : nothing

function _split_parameter_line(line)
    # Julia parses `field::Type ~ geometry` as the infix call `~(field::Type, geometry)`.
    line isa Expr && line.head == :call && line.args[1] == :~ || return nothing
    length(line.args) == 3 || error("parameter declarations must use `field::Type ~ geometry`")
    declaration, geometry = line.args[2], line.args[3]
    declaration isa Expr && declaration.head == :(::) ||
        error("the left side of `~` must be a typed field declaration")
    name = declaration.args[1]
    name isa Symbol || error("parameter field names must be symbols")
    return name, declaration.args[2], geometry
end

function _split_geometry_macro(line)
    line isa Expr && line.head == :macrocall || return nothing
    macro_name = line.args[1]
    macro_name == Symbol("@geometry") || return nothing
    payload = line.args[end]
    payload isa Expr && payload.head == :call && payload.args[1] == :~ ||
        error("use `@geometry (a, b, ...) ~ transformation`")
    lhs, geometry = payload.args[2], payload.args[3]
    names = if lhs isa Symbol
        (lhs,)
    elseif lhs isa Expr && lhs.head == :tuple && all(x -> x isa Symbol, lhs.args)
        Tuple(lhs.args)
    else
        error("@geometry must name one or more fields")
    end
    return names, geometry
end

function _contains_field_reference(expr, fields::Set{Symbol})
    expr isa QuoteNode && return false
    expr isa Symbol && return expr in fields
    expr isa Expr || return false
    return any(arg -> _contains_field_reference(arg, fields), expr.args)
end

function _type_parameter_parts(parameters)
    names = Symbol[]
    for parameter in parameters
        if parameter isa Symbol
            push!(names, parameter)
        elseif parameter isa Expr && parameter.head in (:<:, :>:)
            push!(names, parameter.args[1])
        else
            error("unsupported type parameter `$parameter`")
        end
    end
    return names
end

"""
    @paramorph T struct Model{...,T<:Real}
        auxiliary::A
        parameter::T ~ transform
        child::Child{T} ~ nested(key=value)
    end

Declare parameter geometry next to ordinary Julia storage types. `::` describes
storage; `~` describes geometry. Fields without `~` are auxiliary.

A struct may alternatively declare one coupled geometry:

    @paramorph T struct Interval{T<:Real}
        lower::T
        upper::T
        @geometry (lower, upper) ~ ordered_interval_transform()
    end
"""
macro paramorph(numeric_parameter, expr)
    numeric_parameter isa Symbol || error("the numeric parameter passed to @paramorph must be a symbol")
    expr isa Expr && expr.head == :struct || error("@paramorph must wrap a struct definition")
    expr.args[1] && error("@paramorph does not support mutable structs")

    struct_sig = expr.args[2]
    declaration, supertype = if struct_sig isa Expr && struct_sig.head == :(<:)
        struct_sig.args[1], struct_sig.args[2]
    else
        struct_sig, nothing
    end

    if declaration isa Expr && declaration.head == :curly
        struct_name = declaration.args[1]
        type_params = collect(declaration.args[2:end])
    elseif declaration isa Symbol
        struct_name = declaration
        type_params = Any[]
    else
        error("unsupported struct declaration")
    end
    struct_name isa Symbol || error("unsupported struct name")

    type_args = _type_parameter_parts(type_params)
    numeric_index = findfirst(==(numeric_parameter), type_args)
    numeric_index === nothing && error(
        "numeric parameter $numeric_parameter must be explicitly declared by the struct",
    )
    numeric_parameter_decl = type_params[numeric_index]

    raw_lines = [line for line in expr.args[3].args if !(line isa LineNumberNode)]
    field_records = NamedTuple[]
    geometry_macro = nothing

    for line in raw_lines
        global_geometry = _split_geometry_macro(line)
        if global_geometry !== nothing
            geometry_macro === nothing || error("only one @geometry declaration is allowed")
            geometry_macro = global_geometry
            continue
        end

        parameter = _split_parameter_line(line)
        if parameter !== nothing
            name, storage, geometry = parameter
            push!(field_records, (; name, storage, geometry, is_parameter=true, default=nothing))
            continue
        end

        has_default = line isa Expr && line.head == :(=)
        declaration_line = has_default ? line.args[1] : line
        default = has_default ? line.args[2] : nothing
        name = _field_name_from_decl(declaration_line)
        name === nothing && error(
            "@paramorph struct bodies may contain only typed fields, `field::Type ~ geometry`, and @geometry",
        )
        push!(field_records, (;
            name,
            storage=declaration_line.args[2],
            geometry=nothing,
            is_parameter=false,
            default,
        ))
    end

    field_names = [r.name for r in field_records]
    length(unique(field_names)) == length(field_names) || error("duplicate field declaration")

    if geometry_macro !== nothing
        any(r -> r.is_parameter, field_records) && error(
            "do not mix field-level `~` declarations with a global @geometry declaration",
        )
        geometry_names, global_geometry = geometry_macro
        all(name -> name in field_names, geometry_names) || error("@geometry names an unknown field")
        field_records = [merge(r, (; is_parameter=r.name in geometry_names)) for r in field_records]
    else
        global_geometry = nothing
    end

    parameter_names = Tuple(r.name for r in field_records if r.is_parameter)
    auxiliary_names = Tuple(r.name for r in field_records if !r.is_parameter)
    isempty(parameter_names) && error("@paramorph requires at least one parameter field")

    clean_fields = [:( $(r.name)::$(r.storage) ) for r in field_records]
    all_values = Expr(:tuple, [:( $(r.name) = $(r.name) ) for r in field_records]...)
    defaults = Expr(:tuple, [:( $(r.name) = $(r.default) ) for r in field_records if !r.is_parameter && r.default !== nothing]...)

    field_set = Set(field_names)
    runtime_dependent = if global_geometry === nothing
        any(r -> r.is_parameter && _contains_field_reference(r.geometry, field_set), field_records)
    else
        _contains_field_reference(global_geometry, field_set)
    end

    # Bind every field name while evaluating runtime geometry expressions.
    bind_from_values = [:( $(r.name) = getproperty(values, $(QuoteNode(r.name))) ) for r in field_records]

    if global_geometry === nothing
        value_schema_pairs = Any[]
        type_schema_pairs = Any[]
        parameter_value_pairs = Any[]
        type_reconstruct_pairs = Any[]
        prototype_reconstruct_pairs = Any[]

        for r in field_records
            r.is_parameter || continue
            name, geometry = r.name, r.geometry
            push!(value_schema_pairs, :(
                $name = Paramorph._materialize_geometry(
                    $geometry,
                    fieldtype(S, $(QuoteNode(name))),
                    getproperty(values, $(QuoteNode(name))),
                    true,
                )
            ))
            push!(type_schema_pairs, :(
                $name = Paramorph._materialize_geometry(
                    $geometry,
                    fieldtype(S, $(QuoteNode(name))),
                    nothing,
                    false,
                )
            ))
            push!(parameter_value_pairs, :(
                $name = Paramorph._geometry_value(
                    $geometry,
                    getproperty(values, $(QuoteNode(name))),
                )
            ))
            push!(type_reconstruct_pairs, :(
                $name = Paramorph._reconstruct_geometry(
                    $geometry,
                    fieldtype(S, $(QuoteNode(name))),
                    getproperty(constrained, $(QuoteNode(name))),
                )
            ))
            push!(prototype_reconstruct_pairs, :(
                $name = Paramorph._reconstruct_geometry(
                    $geometry,
                    getfield(prototype, $(QuoteNode(name))),
                    fieldtype(S, $(QuoteNode(name))),
                    getproperty(constrained, $(QuoteNode(name))),
                )
            ))
        end
        value_schema_expr = :(Paramorph.TransformVariables.as($(Expr(:tuple, value_schema_pairs...))))
        type_schema_expr = :(Paramorph.TransformVariables.as($(Expr(:tuple, type_schema_pairs...))))
        parameter_values_expr = Expr(:tuple, parameter_value_pairs...)
        type_reconstructed_parameters = Dict(r.name => pair.args[2] for (r, pair) in zip(
            [r for r in field_records if r.is_parameter], type_reconstruct_pairs,
        ))
        prototype_reconstructed_parameters = Dict(r.name => pair.args[2] for (r, pair) in zip(
            [r for r in field_records if r.is_parameter], prototype_reconstruct_pairs,
        ))
    else
        value_schema_expr = global_geometry
        type_schema_expr = global_geometry
        parameter_values_expr = Expr(:tuple, [:( $name = getproperty(values, $(QuoteNode(name))) ) for name in parameter_names]...)
        type_reconstructed_parameters = Dict(name => :(getproperty(constrained, $(QuoteNode(name)))) for name in parameter_names)
        prototype_reconstructed_parameters = copy(type_reconstructed_parameters)
    end

    # Reconstruction expressions preserve prototype auxiliary values or use declared defaults.
    type_field_values = Any[]
    prototype_field_values = Any[]
    for r in field_records
        if r.is_parameter
            push!(type_field_values, get(type_reconstructed_parameters, r.name, :(getproperty(constrained, $(QuoteNode(r.name))))))
            push!(prototype_field_values, get(prototype_reconstructed_parameters, r.name, :(getproperty(constrained, $(QuoteNode(r.name))))))
        else
            if r.default === nothing
                push!(type_field_values, :(throw(ArgumentError(string(
                    S, " has no default for auxiliary field ", $(string(r.name)), "; use a prototype object",
                )))))
            else
                push!(type_field_values, r.default)
            end
            push!(prototype_field_values, :(getfield(prototype, $(QuoteNode(r.name)))))
        end
    end

    generated_declaration = Expr(:curly, struct_name, type_params...)
    generated_struct_sig = isnothing(supertype) ? generated_declaration : Expr(:(<:), generated_declaration, supertype)

    # Validating and trusted constructors.
    constructor = quote
        function $struct_name{$(type_args...)}(
            ::Paramorph._TrustedConstruction,
            $(clean_fields...),
        ) where {$(type_params...)}
            return new{$(type_args...)}($(field_names...))
        end
        function $struct_name{$(type_args...)}($(clean_fields...)) where {$(type_params...)}
            values = $all_values
            Paramorph.validate_constrained($struct_name{$(type_args...)}, values)
            return new{$(type_args...)}($(field_names...))
        end
    end

    inferred_params = [p for (p, name) in zip(type_params, type_args) if name != numeric_parameter]
    inferred_args = [name for name in type_args if name != numeric_parameter]
    inferred_constructor = if isempty(inferred_args)
        quote
            function $struct_name($(clean_fields...)) where {$numeric_parameter_decl}
                return $struct_name{$(type_args...)}($(field_names...))
            end
        end
    else
        quote
            function $struct_name{$(inferred_args...)}($(clean_fields...)) where {$(inferred_params...), $numeric_parameter_decl}
                return $struct_name{$(type_args...)}($(field_names...))
            end
        end
    end

    generated_body = Expr(:block, clean_fields..., constructor.args...)
    struct_definition = Expr(:struct, false, generated_struct_sig, generated_body)

    rebound_args = [name == numeric_parameter ? :ParamorphNumeric : name for name in type_args]

    type_schema_body = runtime_dependent ? :(throw(ArgumentError(string(
        S, " has parameter geometry depending on runtime field values; use a prototype object",
    )))) : type_schema_expr

    return esc(quote
        $struct_definition
        $inferred_constructor

        Paramorph.is_paramorph_type(::Type{<:$struct_name}) = true
        Paramorph.parameter_fields(::Type{<:$struct_name}) = $parameter_names
        Paramorph.auxiliary_fields(::Type{<:$struct_name}) = $auxiliary_names
        function Paramorph.auxiliary_defaults(
            ::Type{<:$struct_name{$(type_args...)}}
        ) where {$(type_params...)}
            return $defaults
        end
        Paramorph.numeric_type(::Type{<:$struct_name{$(type_args...)}}) where {$(type_params...)} = $numeric_parameter
        Paramorph.supports_type_geometry(::Type{<:$struct_name}) = $(!runtime_dependent)

        function Paramorph.rebind_numeric_type(
            ::Type{<:$struct_name{$(type_args...)}},
            ::Type{ParamorphNumeric},
        ) where {$(type_params...), ParamorphNumeric<:Real}
            return $struct_name{$(rebound_args...)}
        end

        function Paramorph._schema_from_values(
            ::Type{S}, values::NamedTuple, context::NamedTuple,
        ) where {$(type_params...), S<:$struct_name{$(type_args...)}}
            $(bind_from_values...)
            return $value_schema_expr
        end

        function Paramorph.transformation_schema(
            object::S, context::NamedTuple=NamedTuple(),
        ) where {$(type_params...), S<:$struct_name{$(type_args...)}}
            values = NamedTuple{fieldnames(S)}(Tuple(getfield(object, f) for f in fieldnames(S)))
            return Paramorph._schema_from_values(S, values, context)
        end

        function Paramorph.transformation_schema(
            ::Type{S}, context::NamedTuple=NamedTuple(),
        ) where {$(type_params...), S<:$struct_name{$(type_args...)}}
            return $type_schema_body
        end

        function Paramorph._parameter_values_from_values(
            ::Type{S}, values::NamedTuple, context::NamedTuple,
        ) where {$(type_params...), S<:$struct_name{$(type_args...)}}
            $(bind_from_values...)
            return $parameter_values_expr
        end

        function Paramorph._reconstruct_declared_from_type(
            ::Type{S}, constrained::NamedTuple, context::NamedTuple,
        ) where {$(type_params...), S<:$struct_name{$(type_args...)}}
            $(runtime_dependent ? :(throw(ArgumentError(string(
                S, " has value-dependent parameter geometry; use a prototype object",
            )))) : nothing)
            return S(Paramorph._trusted_construction, $(type_field_values...))
        end

        function Paramorph._reconstruct_declared_from_prototype(
            prototype::$struct_name,
            ::Type{S},
            constrained::NamedTuple,
            context::NamedTuple,
        ) where {$(type_params...), S<:$struct_name{$(type_args...)}}
            values = NamedTuple{fieldnames(typeof(prototype))}(
                Tuple(getfield(prototype, f) for f in fieldnames(typeof(prototype)))
            )
            $(bind_from_values...)
            return S(Paramorph._trusted_construction, $(prototype_field_values...))
        end
    end)
end

